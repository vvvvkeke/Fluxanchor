class Smiles_data:
    def __init__(self, cls_repr, atomic_coords, atomic_reprs, atomic_symbol):
        self.cls_repr = cls_repr  ### Molecular overall embedding
        self.atomic_coords = atomic_coords  ### Molecular 3D coordinates
        self.atomic_reprs = atomic_reprs  ### Molecular feature attributes
        self.atomic_symbol = atomic_symbol  ### Molecular atomic symbols


clf = UniMolRepr(data_type='molecule', remove_hs=False)


def check_smiles_atom_count(smiles, max_atoms=256):
    """
    Check the number of atoms in SMILES (after adding hydrogens)
    Args:
        smiles: SMILES string
        max_atoms: Maximum allowed number of atoms
    Returns:
        (is_valid, num_atoms, error_msg)
    """
    try:
        mol = Chem.MolFromSmiles(smiles)
        if mol is None:
            return False, 0, "RDKit cannot parse SMILES"

        # Number of atoms after adding hydrogens
        mol_with_h = Chem.AddHs(mol)
        num_atoms = mol_with_h.GetNumAtoms()

        if num_atoms > max_atoms:
            return False, num_atoms, f"Atom count exceeds limit: {num_atoms} > {max_atoms}"

        if num_atoms == 0:
            return False, 0, "Molecule has no atoms"

        return True, num_atoms, None
    except Exception as e:
        return False, 0, f"Check failed: {str(e)}"


def save_smiles_tensor(i, path, unimol_repr, types):
    """
    Save the molecular representation generated by UniMol
    Args:
        i: Index (consecutive)
        path: Save path
        unimol_repr: UniMol representation
        types: substrate or product
    """
    data = Smiles_data(cls_repr=unimol_repr["cls_repr"], atomic_coords=unimol_repr["atomic_coords"],
                       atomic_reprs=unimol_repr["atomic_reprs"], atomic_symbol=unimol_repr["atomic_symbol"])
    with open(os.path.join(path, f"{types}/unimol_repr_{i}_{types}.pkl"), 'wb') as file:
        pickle.dump(data, file)


def process_smiles_batch(batch_data):
    """
    Batch process SMILES of substrate and product
    Args:
        batch_data: list of dict, each dict contains:
            - 'original_index': Original index
            - 'smiles_substrate': substrate SMILES
            - 'smiles_product': product SMILES
            - 'row': Original data row
    Returns:
        (success_list, failed_indices)
        - success_list: List of successfully processed data
        - failed_indices: List of failed original indices
    """
    if not batch_data:
        return [], []

    try:
        # Collect all substrate and product SMILES
        substrate_smiles_list = [item['smiles_substrate'] for item in batch_data]
        product_smiles_list = [item['smiles_product'] for item in batch_data]

        # Batch process substrate
        substrate_reprs = clf.get_repr(substrate_smiles_list, return_atomic_reprs=True)

        # Batch process product
        product_reprs = clf.get_repr(product_smiles_list, return_atomic_reprs=True)

        # Validate return results
        if substrate_reprs is None or product_reprs is None:
            logging.warning(f"Batch processing failed: UniMol returned None")
            return [], [item['original_index'] for item in batch_data]

        # Check required fields
        required_fields = ["cls_repr", "atomic_coords", "atomic_reprs", "atomic_symbol"]
        for field in required_fields:
            if field not in substrate_reprs or field not in product_reprs:
                logging.warning(f"Batch processing failed: Missing required field {field}")
                return [], [item['original_index'] for item in batch_data]

        # Process results for each sample
        success_list = []
        failed_indices = []

        for i, item in enumerate(batch_data):
            try:
                # Extract representation for the i-th sample
                substrate_repr = {
                    'cls_repr': substrate_reprs['cls_repr'][i:i+1],
                    'atomic_coords': substrate_reprs['atomic_coords'][i:i+1],
                    'atomic_reprs': substrate_reprs['atomic_reprs'][i:i+1],
                    'atomic_symbol': substrate_reprs['atomic_symbol'][i:i+1]
                }

                product_repr = {
                    'cls_repr': product_reprs['cls_repr'][i:i+1],
                    'atomic_coords': product_reprs['atomic_coords'][i:i+1],
                    'atomic_reprs': product_reprs['atomic_reprs'][i:i+1],
                    'atomic_symbol': product_reprs['atomic_symbol'][i:i+1]
                }

                success_list.append({
                    'original_index': item['original_index'],
                    'substrate_repr': substrate_repr,
                    'product_repr': product_repr,
                    'row': item['row']
                })

            except Exception as e:
                logging.warning(f"Failed to extract results for index {item['original_index']}: {str(e)}")
                failed_indices.append(item['original_index'])

        return success_list, failed_indices

    except Exception as e:
        logging.warning(f"Batch processing SMILES failed: {str(e)}")
        return [], [item['original_index'] for item in batch_data]


if __name__ == '__main__':
    parser = argparse.ArgumentParser()
    parser.add_argument("--input_dir", type=str, default="../predict/iECDH1ME8569_1439")
    parser.add_argument("--update_tsv", action="store_true",
                       help="Whether to update input.tsv and reassign consecutive indices (requires rerunning all prerequisite steps)")
    parser.add_argument("--batch_size", type=int, default=32,
                       help="Batch size for batch processing, default 32")
    args = parser.parse_args()
    path = args.input_dir

    # Setup logging
    log_file = os.path.join(path, "dataset/unimol_processing.log")
    logging.basicConfig(
        level=logging.INFO,
        format="%(asctime)s - %(levelname)s - %(message)s",
        handlers=[
            logging.FileHandler(log_file, mode='w'),
            logging.StreamHandler()
        ]
    )

    create_directory_if_not_exists(os.path.join(path, "dataset/Smiles/substrate"))
    create_directory_if_not_exists(os.path.join(path, "dataset/Smiles/product"))

    # Read raw data
    input_file = os.path.join(path, "dataset/input.tsv")
    df = pd.read_csv(input_file, sep="\t", encoding="utf-8")
    pkl_path = os.path.join(path, "dataset/Smiles")

    total_rows = len(df)
    batch_size = args.batch_size
    logging.info(f"Start processing, total {total_rows} rows of data, batch_size={batch_size}")
    print(f"Start processing, total {total_rows} rows of data, batch_size={batch_size}")

    if args.update_tsv:
        logging.info("Enabled --update_tsv mode: will filter data and reassign consecutive indices")
        print("⚠️  Enabled --update_tsv mode: will filter data and reassign consecutive indices")
        print("⚠️  Warning: This mode requires rerunning all prerequisite steps (ESM, PDB, DSSP, LLM)")
        print()

    # For saving successfully processed rows and corresponding new indices
    valid_rows = []
    failed_indices = []
    new_index = 0  # Consecutive index

    # Batch processing related variables
    current_batch = []
    processed_count = 0

    def process_current_batch():
        """Process current batch of data"""
        global new_index  # Declare global variable to be modified

        if not current_batch:
            return

        print(f"\nBatch processing {len(current_batch)} samples...")
        logging.info(f"Batch processing {len(current_batch)} samples")

        # Batch process SMILES
        success_list, batch_failed_indices = process_smiles_batch(current_batch)

        # Record failed indices
        failed_indices.extend(batch_failed_indices)
        if batch_failed_indices:
            logging.warning(f"{len(batch_failed_indices)} samples failed in batch processing: {batch_failed_indices}")
            print(f"  ⚠️  {len(batch_failed_indices)} samples failed in batch processing")

        # Save successful results - reassign consecutive new_index
        for item in success_list:
            try:
                # Use current new_index (instead of pre-allocated)
                actual_new_index = new_index
                save_smiles_tensor(actual_new_index, pkl_path, item['substrate_repr'], "substrate")
                save_smiles_tensor(actual_new_index, pkl_path, item['product_repr'], "product")

                # Add to valid rows list
                valid_rows.append(item['row'])

                if item['original_index'] != actual_new_index:
                    logging.info(f"Success: Original index {item['original_index']} -> New index {actual_new_index}")
                    print(f"  ✓ Index {actual_new_index} (Original index: {item['original_index']})")
                else:
                    logging.info(f"Success: Index {actual_new_index}")
                    print(f"  ✓ Index {actual_new_index}")

                new_index += 1  # Increment only on successful save

            except Exception as e:
                logging.error(f"Save failed for original index {item['original_index']}: {str(e)}")
                failed_indices.append(item['original_index'])
                print(f"  ❌ Save failed for index {item['original_index']}: {str(e)}")

                # Clean up potentially saved files
                substrate_file = os.path.join(pkl_path, f"substrate/unimol_repr_{new_index}_substrate.pkl")
                product_file = os.path.join(pkl_path, f"product/unimol_repr_{new_index}_product.pkl")
                if os.path.exists(substrate_file):
                    os.remove(substrate_file)
                if os.path.exists(product_file):
                    os.remove(product_file)

        # Clear current batch
        current_batch.clear()

    for original_index, row in df.iterrows():
        processed_count += 1
        if processed_count % 100 == 0 or processed_count == 1:
            print(f"Validation progress: {processed_count}/{total_rows} ({processed_count*100.0/total_rows:.1f}%)")
        logging.info(f"Validating original index {original_index}")

        # Check if protein sequence contains X or U
        protein = row["sequence"]
        if "X" in protein or "U" in protein:
            logging.warning(f"Skipping original index {original_index}: Protein sequence contains X or U")
            failed_indices.append(original_index)
            continue

        # Check protein sequence length
        if len(protein) > 2048:
            logging.warning(f"Skipping original index {original_index}: Protein sequence too long (length: {len(protein)})")
            failed_indices.append(original_index)
            continue

        smiles_substrate = row["smiles_substrate"]
        smiles_product = row["smiles_product"]

        # Check SMILES atom count (UniMol limit is 256)
        sub_valid, sub_atoms, sub_error = check_smiles_atom_count(smiles_substrate, max_atoms=256)
        prod_valid, prod_atoms, prod_error = check_smiles_atom_count(smiles_product, max_atoms=256)

        if not sub_valid:
            logging.warning(f"Skipping original index {original_index}: Substrate SMILES check failed - {sub_error}")
            failed_indices.append(original_index)
            continue

        if not prod_valid:
            logging.warning(f"Skipping original index {original_index}: Product SMILES check failed - {prod_error}")
            failed_indices.append(original_index)
            continue

        logging.info(f"  SMILES atom count check passed: substrate={sub_atoms}, product={prod_atoms}")

        # Passed all validations, add to current batch
        current_batch.append({
            'original_index': original_index,
            'smiles_substrate': smiles_substrate,
            'smiles_product': smiles_product,
            'row': row
        })

        # When batch is full, process current batch
        if len(current_batch) >= batch_size:
            process_current_batch()

    # Process last batch (may not be full batch_size)
    if current_batch:
        print(f"\nProcessing last batch...")
        process_current_batch()

    # Save updated input.tsv (only contains successfully processed rows)
    if valid_rows:
        valid_df = pd.DataFrame(valid_rows)
        # Reset index to consecutive numbers
        valid_df.reset_index(drop=True, inplace=True)

        # Backup original file
        backup_file = os.path.join(path, "dataset/input_original.tsv")
        if not os.path.exists(backup_file):
            df.to_csv(backup_file, sep="\t", index=False, encoding="utf-8")
            logging.info(f"Original data backed up to: {backup_file}")

        # Save filtered data
        valid_df.to_csv(input_file, sep="\t", index=False, encoding="utf-8")
        logging.info(f"Updated input.tsv, retained {len(valid_df)} rows of valid data")

    # Output statistics
    print("\n" + "="*60)
    logging.info("="*60)
    logging.info(f"Processing completion statistics:")
    logging.info(f"  Total rows: {total_rows}")
    logging.info(f"  Successfully processed: {new_index} rows")
    logging.info(f"  Failed/skipped: {len(failed_indices)} rows")

    print(f"Processing completed!")
    print(f"  Total rows: {total_rows}")
    print(f"  Successfully processed: {new_index} rows")
    print(f"  Failed/skipped: {len(failed_indices)} rows")

    if failed_indices:
        logging.info(f"  Failed original indices: {failed_indices}")
        print(f"  Failed original indices: {failed_indices}")

    logging.info(f"Generated file indices: 0 to {new_index - 1} (consecutive)")
    print(f"Generated file indices: 0 to {new_index - 1} (consecutive)")
    print(f"Original data backed up to: {backup_file}")
    print(f"Detailed log saved at: {log_file}")
    logging.info("="*60)
